interface LanguageState {
  language: Language;
  toggleLanguage: () => void;
  setLanguage: (lang: Language) => void;
  t: (key: string, fallback?: string) => string;
  translateNutrient: (nutrient: string) => string;
  translateReason: (reason: string) => string;
}

export const useLanguageStore = create<LanguageState>((set, get) => ({
  language: (localStorage.getItem('checkpoint_language') as Language) || 'en',
  toggleLanguage: () =>
    set((state) => {
      const nextLang: Language = state.language === 'en' ? 'hi' : 'en';
      localStorage.setItem('checkpoint_language', nextLang);
      return { language: nextLang };
    }),
  setLanguage: (lang) => {
    localStorage.setItem('checkpoint_language', lang);
    set({ language: lang });
  },
  t: (key, fallback) => {
    const lang = get().language;
    const entry = TRANSLATIONS[key];
    if (!entry) return fallback || key;
    return entry[lang] || entry.en || fallback || key;
  },
  translateNutrient: (nutrient: string) => {
    const lang = get().language;
    if (lang === 'en') return nutrient;
    const clean = nutrient.trim().toLowerCase();
    return NUTRIENT_TRANSLATIONS[clean] || nutrient;
  },
  translateReason: (reason: string) => {
    const lang = get().language;
    if (lang === 'en') return reason;
    for (const item of REASON_TRANSLATIONS) {
      if (item.match.test(reason)) {
        return item.hi;
      }
    }
    return reason;
  },
}));
